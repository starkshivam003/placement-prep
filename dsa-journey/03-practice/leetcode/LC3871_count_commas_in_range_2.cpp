class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000){
            return 0;
        }
        if(n<1000000){
            return (n-1000+1);
        }
        if(n<1000000000){
            return 2*(n-1000000+1)+999000;
        }
        if(n<1000000000000){
            return 3*(n-1000000000+1)+(2*999000000+999000);
        }
        if(n<1000000000000000){
            return 4*(n-1000000000000+1)+(3*999000000000+2*999000000+999000);
        }
        return 5+(4*999000000000000+3*999000000000+2*999000000+999000);
    }
};
